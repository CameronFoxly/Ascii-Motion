#!/usr/bin/env tsx
/**
 * Generate the portable MCP bridge artifacts consumed by ascii-motion-mcp and the docs site:
 *
 *   src/mcp/contract/bridge-contract.json        operation/message JSON Schemas + contract hash
 *   src/mcp/contract/contractHash.generated.ts   hash the browser announces in `hello`
 *   src/mcp/coverage-manifest.json               feature → operation coverage manifest
 *   docs/MCP_BRIDGE_OPERATIONS.md                generated operation reference
 *
 *   npm run mcp:contract          # write all artifacts
 *   npm run mcp:contract:check    # fail if any committed artifact is stale
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildBridgeContract } from '../src/mcp/contract/artifact';
import { buildCoverageManifest, FEATURE_COVERAGE } from '../src/mcp/contract/coverage';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const contract = buildBridgeContract((text) => createHash('sha256').update(text).digest('hex'));

function operationsReference(): string {
  const lines = [
    '# MCP bridge operation reference',
    '',
    '<!-- Generated by scripts/generate-mcp-contract.ts from src/mcp/contract — do not edit. Run `npm run mcp:contract`. -->',
    '',
    `Contract ${contract.contractVersion} · protocol v${contract.protocolVersion} · hash \`${contract.contractHash.slice(0, 12)}\` · ${contract.operations.length} operations.`,
    'Full input/result JSON Schemas live in `src/mcp/contract/bridge-contract.json`; see `docs/MCP_BRIDGE_CONTRACT.md` for the protocol and contributor workflow.',
    '',
    'Kinds: **read** (no change), **view** (UI/view state, not part of the saved document, no undo), **mutation** (one revision + one undo entry, rolled back on failure), **io** (export/cloud).',
    '`destructive: no` means purely additive. `requires` lists auth/entitlement checks that return `AUTH_REQUIRED` / `ENTITLEMENT_REQUIRED`.',
    '',
  ];
  const domains = [...new Set(contract.operations.map((o) => o.domain))];
  for (const domain of domains) {
    lines.push(`## ${domain}`, '', '| Operation | Kind | Destructive | Requires | Description |', '| --- | --- | --- | --- | --- |');
    for (const o of contract.operations.filter((op) => op.domain === domain)) {
      lines.push(`| \`${o.name}\` | ${o.kind} | ${o.destructive ? 'yes' : 'no'} | ${o.requires.join(', ') || '—'} | ${o.description.replace(/\\/g, '\\\\').replace(/\|/g, '\\|')} |`);
    }
    lines.push('');
  }
  lines.push('## exclusions', '', 'Exclusions, partial coverage and runtime limits from `src/mcp/coverage-manifest.json`:', '');
  for (const f of FEATURE_COVERAGE.filter((entry) => entry.status !== 'supported' || entry.reason)) {
    lines.push(`- **${f.title}** (\`${f.id}\`, ${f.status}): ${f.reason ?? ''}`);
  }
  lines.push('');
  return lines.join('\n');
}

const outputs: Array<[string, string]> = [
  ['src/mcp/contract/bridge-contract.json', `${JSON.stringify(contract, null, 2)}\n`],
  ['src/mcp/contract/contractHash.generated.ts', `// Generated by scripts/generate-mcp-contract.ts — do not edit.\nexport const BRIDGE_CONTRACT_HASH = '${contract.contractHash}';\n`],
  ['src/mcp/coverage-manifest.json', `${JSON.stringify(buildCoverageManifest(contract), null, 2)}\n`],
  ['docs/MCP_BRIDGE_OPERATIONS.md', operationsReference()],
];

const summary = `${contract.operations.length} operations, hash ${contract.contractHash.slice(0, 12)}`;
if (process.argv.includes('--check')) {
  const stale = outputs.filter(([path, text]) => {
    try {
      return readFileSync(resolve(root, path), 'utf8') !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`MCP bridge artifacts are out of date: ${stale.map(([p]) => p).join(', ')}. Run \`npm run mcp:contract\` and commit the result.`);
    process.exit(1);
  }
  console.log(`MCP bridge artifacts are up to date (${summary})`);
} else {
  for (const [path, text] of outputs) writeFileSync(resolve(root, path), text);
  console.log(`Wrote ${outputs.map(([p]) => p).join(', ')} (${summary})`);
}
